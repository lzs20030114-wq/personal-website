/**
 * 项目二 · 阵列过渡（Lab.08 的键谱序列）——纯数据，零 DOM。
 *
 * 用户 2026-08-19 立项：「想象每一个竖向的是一个单元，可能这个单元很窄。
 * 左边是第二个（蘑菇挑台），右边是第四个（阶梯方箱），中间存在十个单元，
 * 每一个单元都有微小的形变，最后实现从 2 到 4 的过渡。」
 * 这是交接件「下一步任务①：单元阵列化——多根带子、不同键谱」的第一口。
 *
 * v2（2026-08-20 用户拍板线稿系列后接回）：首版只插值 rb，被用户否决——
 * 「转变根本不平滑」。线稿诊断（真引擎终态剖面 + 相邻形态距离指标）查明：
 * 方箱的「方」来自端面找平 panel 与 boxSquare 整形，不来自 rb，首版把全部
 * 形变堆在末格二值切换（断层 = 其他步的 7 倍）。返工流程 = 先出纯线稿系列 →
 * 用户确认形态 → 才接回台架（工作纪律，用户 2026-08-20 立）。
 *
 * 定版序列的三个渐进杠杆：
 * - **rb 键长 0.10→0.32 线性**（步长恒 0.02）；
 * - **boxSquare 强度 0→1 渐入**（引擎 2026-08-20 新增数字强度：贴轴/找平/
 *   压肩按强度混入；端面硬投影按弦弧比 0.85→1 平滑爬坡另行渐入）——
 *   「变方」从第 2 格就开始渗入，不在任何一格二值启用；
 * - **panel 端面找平提前在低强度段走完到全跨 ±8**（半跨渐入是假杠杆：
 *   不到 ±8 端面投影不参与；到达那一格的跳变要放在 sq 还小的位置）。
 * 线稿实测相邻形态距离全 12 步落在 0.69–1.76（均值 1.30，最大/最小 2.6×），
 * 对比首版 0.72–5.17（7.2×）。两个端点的**形态**仍是站上原谱（蘑菇 = 全套站方
 * 修正、阶梯 = boxSquare 全量；键位图只整体平移、跨度集与键长逐位不动），
 * 等长键与「键谱两端 ≥4 节缓冲」全程守住。
 *
 * ## 对位：解析构造，不是标定表（2026-08-22 定案）
 *
 * 用户要的是一条规律（「根据理想的最终形态反推位置，然后寻找出一个规律」），
 * 基准取**嘴心**（最外键对的中点 = 折叠体与竖带的接合处，用户 2026-08-20 拍板；
 * 体心与嘴心相差各形态自身的下垂量 Δ，全族差 2.8px ⇒ 二者不可能同时对齐）。
 *
 * 终态时轴上的账是封闭的：
 *   S = (f−1)·SEG·r      自由段的轴向跨度（SEG·100 = 2px/节，故 S = 2(f−1)r px）
 *   M = 100·rb           嘴在轴上占的高度 —— **理想终态的高度由它定义**
 *   S − M                剩给上下缓冲的轴向余量，按节数比 bT:bB 分掉
 *   嘴心(r) = 2·lead + (S − M)·φ + M/2 ，  φ = bT/(bT+bB)
 *           = [2·lead + M·(1/2 − φ)] + [2(f−1)·φ]·r
 *
 * 读这个式子就能看出**不需要标定**：
 * - 令 **φ = 1/2**（上下缓冲等长 ⇒ 扇形正居中在自由段上），M 那一项直接消失；
 * - 再令全员 **lead 与 f 相同**，则 嘴心(r) = 2·lead + (f−1)·r ——
 *   **与键长、与形态、与梯挡数全都无关，在每一个 r 上逐位相等**。
 * 即：三段等长（lead / f / tail 全员同值）+ 扇形正居中，对齐就是构造出来的，
 * 收缩早期误差**严格为零**，不必逐单元试凑。此前两轮的标定表（DFAN/LEAD/TAIL）
 * 就此退役——它们是在 φ≠1/2、f 各异的前提下补偿出来的，前提消掉后不再需要。
 *
 * 实测（12 条同步推进，四个检查点）：早期散布 0.000 / 0.000，终态 0.73px。
 * 残留 0.91px **不是放置误差**，是形态自身的材料不对称——上下缓冲拉伸不等，
 * 把嘴心从自由段几何中点拽开（自由段几何中点本身全族散布仅 0.18px，账是准的）。
 * 它随「方化到什么程度」变化，不可能用节点整数位（lead 的量子 = 2px/节）抹平；
 * 能压的只有富余材料本身——故 FREE 取纪律允许的最小值（见下）。
 * 对比历史：首版标定 4.78px（早期）/ 1.01px（终态），二轮四检查点标定 1.93px。
 *
 * 边界申明：交接件明令「行为矩阵 → 键谱的翻译规则由使用者手写」。这里的序列
 * 只是两张既有键谱之间的形态学串联（演示编排，形态经用户线稿拍板），不是那套
 * 翻译规则；用户交来正式规则后本文件随时按其替换。
 */
import { SKIN_ROOT_FIX, type SkinSeg, type SkinSpec, type SkinUnitOpts } from './skin-unit';
import { SKIN_UNITS, fan, skinSiteOpts } from './skin-data';

export interface SkinArrayUnit {
  /** 过渡参数 0..1（0 = 蘑菇挑台，1 = 阶梯方箱） */
  t: number;
  spec: SkinSpec;
  opts: SkinUnitOpts;
  smooth: readonly [number, number];
}

/** 定版时间表（用户 2026-08-20 线稿拍板；端点两格的形态另取原谱，此处只占位） */
const RB = [0.10, 0.12, 0.14, 0.16, 0.18, 0.20, 0.22, 0.24, 0.26, 0.28, 0.30, 0.32];
const PW = [0, 0, 0, 2, 4, 6, 8, 8, 8, 8, 8, 8];
const SQ = [0, 0, 0.05, 0.12, 0.20, 0.30, 0.40, 0.51, 0.61, 0.70, 0.85, 1];

/**
 * 对位构造（**全员同值**，这就是那条规律的全部参数）：
 * lead = 贴合段节数（2px/节，把折叠体整体推到画面中央的高度）；
 * FREE = 自由段节数（全员相同 ⇒ 嘴心随 r 的斜率相同）；
 * TAIL = 尾段，配平总长使帘子下缘齐（尾段钉轴、不对折叠体施力，纯外观量）。
 * 扇形一律居中在自由段上（中心 = (FREE−1)/2）⇒ 上下缓冲等长 ⇒ φ = 1/2。
 */
const LEAD = 54;
const FREE = 61;
const TAIL = 57;
// FREE 取 61 是**下限**：kMax=26 的那六条带缓冲只剩 4 节，再小就吃穿交接件的
// 「键谱两端 ≥4 节缓冲」纪律。取下限是有理由的——自由段越长、富余材料越多，
// 上下缓冲的拉伸越不对称，终态残留越大（实测全程最大散布：f=61 0.73 /
// f=63 0.91 / f=65 1.10 / f=67 1.35px）。形态不受影响（终态高度逐位相同、
// 凸出宽度整体窄 1%、锁定键集合不变）。

/** 带总长（所有单元相同——守门用） */
export const ARRAY_TOTAL = LEAD + FREE + TAIL;
/** 自由段节数（守门/工具用：端点形态被搬到这个长度的自由段上） */
export const ARRAY_FREE = FREE;
/** 自由段的扇形对位中心（= 正中） */
export const ARRAY_CENTER = (FREE - 1) / 2;

/**
 * 把原谱的键位图（含端面面板）搬到对位构造的自由段上：整体平移到正中、
 * 段长换成 FREE。**跨度集 / 键长 / 面板跨度逐位不动 ⇒ 形态不变**；
 * 变的只有它在带子上的位置与两端缓冲的长度——按用户 2026-08-20 拍板，
 * 那些是位置量，不属形态。
 */
function place(seg: SkinSeg): SkinSeg {
  const bonds = seg[2]!;
  const d = ARRAY_CENTER - (bonds[0][0] + bonds[0][1]) / 2;
  const moved = bonds.map(([i, j, rb]) => [i + d, j + d, rb] as const);
  return seg.length === 4
    ? ['f', FREE, moved, seg[3].map(([a, b]) => [a + d, b + d] as const)]
    : ['f', FREE, moved];
}

/** 左右端点 + 10 级中间单元 = 12 条带（定版表只支持这一个规模） */
export function buildTransitionArray(): SkinArrayUnit[] {
  const A = SKIN_UNITS.find((d) => d.key === 'bulb')!;
  const B = SKIN_UNITS.find((d) => d.key === 'stepped')!;
  const n = RB.length;
  const out: SkinArrayUnit[] = [];
  for (let i = 0; i < n; i++) {
    const t = i / (n - 1);
    let seg: SkinSeg;
    let opts: SkinUnitOpts;
    let smooth: readonly [number, number];
    if (i === 0 || i === n - 1) {
      // 端点：**形态**逐字取原谱（键位图的跨度集/键长/面板跨度全不动，即用户逐轮
      // 磨定的那两台），只把它搬到对位构造的自由段正中
      const d = i === 0 ? A : B;
      seg = place(d.spec[1]);
      opts = skinSiteOpts(d);
      smooth = i === 0 ? (A.smooth ?? [3, 1]) : [3, 1];
    } else {
      let kMax = 24 + 2 * Math.round(t); // 梯挡数的唯一离散跳变（t=0.5 加一颗）
      // 键谱两端 ≥4 节缓冲（交接件纪律）——放不下就退一级
      while (ARRAY_CENTER - kMax < 4) kMax -= 2;
      const bonds = fan(ARRAY_CENTER, 8, kMax + 1, 2, RB[i]);
      seg =
        PW[i] > 0
          ? ['f', FREE, bonds, [[ARRAY_CENTER - PW[i], ARRAY_CENTER + PW[i]]]]
          : ['f', FREE, bonds];
      opts = { ...SKIN_ROOT_FIX };
      if (SQ[i] > 0) opts.boxSquare = SQ[i];
      // 绘图平滑：低强度段梯身微皱仍要 [5,2] 盖住；sq≥0.5 后箱体自带压平，回 [3,1]
      smooth = SQ[i] >= 0.5 ? [3, 1] : [5, 2];
    }
    out.push({ t, spec: [['g', LEAD], seg, ['g', TAIL]], opts, smooth });
  }
  return out;
}
